export function getMasterItemId(
  tier: number,
  rarity: 'common' | 'uncommon' | 'eliteRare' | 'bossRare',
  category: ItemCategory,
  name: string,
): number {
  const id = MASTER_ITEM_ID_INDEX[`${tier}|${rarity}|${category}|${name}`];
  if (id === undefined) {
    throw new Error(`Missing master item ID for ${tier}|${rarity}|${category}|${name}`);
  }
  return id;
}

