import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE_MECHANIC_REGISTRY } from '../src/game/mechanics/mechanicRegistry.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'docs/mechanic-inventory.md');
const check = process.argv.includes('--check');

function cell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function bindingSummary(definition, field) {
  return definition.bindings.map((binding) => {
    const prefix = `${binding.scope}:${binding.authority}`;
    const values = field === 'randomness'
      ? [binding.randomness]
      : field === 'implementation'
        ? binding.implementationFiles
        : binding.testFiles;
    return `${prefix}=${values.join(', ')}`;
  }).join('; ');
}

const definitions = CORE_MECHANIC_REGISTRY.list();
const abilityCount = definitions.filter((entry) => entry.kind === 'ability').length;
const terrainCount = definitions.filter((entry) => entry.kind === 'terrain').length;
const rows = definitions.map((definition) => {
  const category = definition.kind === 'ability' ? definition.category : 'terrain';
  const ownership = definition.kind === 'ability' ? definition.battleOwnership : '-';
  const maxLevel = definition.kind === 'ability' ? definition.maxLevel : '-';
  const timing = definition.kind === 'ability' && definition.timing
    ? `${definition.timing.phase}${definition.timing.priority}`
    : '-';
  const localization = definition.kind === 'ability'
    ? [definition.presentation.nameKey, definition.presentation.labelKey, definition.presentation.descriptionKey].filter(Boolean).join('; ')
    : `${definition.presentation.labelKey}; ${definition.presentation.descriptionKey}`;
  return `| ${cell(definition.key)} | ${definition.kind} | ${cell(definition.runtimeId)} | ${definition.wireId} | ${category} | ${ownership} | ${maxLevel} | ${timing} | ${cell(bindingSummary(definition, 'randomness'))} | ${cell(localization)} | ${cell(bindingSummary(definition, 'implementation'))} | ${cell(bindingSummary(definition, 'tests'))} |`;
});

const content = `# Core Mechanic Inventory

Generated by \`npm run mechanics:inventory\`. Do not edit by hand.

- Abilities: ${abilityCount}
- Terrains: ${terrainCount}
- Total mechanics: ${definitions.length}
- Wire-ID authority: \`native/battle_protocol.def\`
- Architecture decision: \`docs/mechanic-extensibility-architecture.md\`

Timing is recorded only when the current glossary metadata supplies both phase and priority. A mechanic may have multiple scoped bindings, but each scope has one authority.

| Mechanic key | Kind | Runtime ID | Wire ID | Category | Battle ownership | Max level | Timing | RNG ownership | Localization keys | Implementation locations | Test locations |
|-|-|-|-:|-|-|-:|-|-|-|-|-|
${rows.join('\n')}
`;

if (check) {
  if (readFileSync(outputPath, 'utf8') !== content) throw new Error(`Generated mechanic inventory is stale: ${outputPath}`);
} else {
  writeFileSync(outputPath, content);
  console.log(`Generated ${outputPath}`);
}
