import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Type } from '@sinclair/typebox';

const root = process.cwd();
const specificationPath = resolve(root, 'Specification_9.1.4_API_DETAIL.md');
const desktopOutputPath = resolve(root, 'desktop/api-v1-contract.json');
const typescriptOutputPath = resolve(root, 'src/api/v1/generatedOperationCatalog.ts');
const check = process.argv.includes('--check');

const specification = readFileSync(specificationPath, 'utf8');
const rowPattern = /^\| (GET|POST) \| `([^`]+)` \| (Public|Bootstrap|Session) \| ([^|]+?) \|$/gm;
const operations = [...specification.matchAll(rowPattern)].map((match) => ({
  method: match[1],
  path: match[2],
  access: match[3].toLowerCase(),
  purpose: match[4].trim(),
  operationId: match[2].slice('/api/v1/'.length),
}));

if (operations.length !== 83) {
  throw new Error(`Expected 83 /api/v1 operations, found ${operations.length}.`);
}

const unique = new Set(operations.map(({ method, path }) => `${method} ${path}`));
if (unique.size !== operations.length) throw new Error('Duplicate /api/v1 method/path pair in the endpoint index.');
if (operations.some(({ path }) => !path.startsWith('/api/v1/'))) throw new Error('Non-v1 route found in the v1 endpoint index.');

const identityProperties = {
  userId: Type.String({ pattern: '^[A-Za-z0-9_-]{1,16}$' }),
  environment: Type.Union(['dev', 'beta', 'orca', 'prod', 'desktop'].map(Type.Literal)),
  gameMode: Type.Union([Type.Literal('normal'), Type.Literal('orca')]),
  levelOffsetForOrca: Type.Optional(Type.Integer({ minimum: 0, maximum: 20 })),
};
const requestSchemas = {
  signUp: Type.Object({ ...identityProperties, language: Type.Optional(Type.Union(['ja', 'en', 'zh-CN', 'zh-TW', 'ko'].map(Type.Literal))) }, { additionalProperties: false }),
  logIn: Type.Object(identityProperties, { additionalProperties: false }),
  logOut: Type.Object({}, { additionalProperties: false }),
  commit: Type.Object({
    expectedRevision: Type.Integer({ minimum: 0 }),
    idempotencyKey: Type.String({ minLength: 16, maxLength: 128, pattern: '^[\\x20-\\x7e]+$' }),
    parameters: Type.Object({}, { additionalProperties: true }),
    confirmationToken: Type.Optional(Type.String({ minLength: 1, maxLength: 512 })),
  }, { additionalProperties: false }),
  simulationRun: Type.Object({ expectedRevision: Type.Optional(Type.Integer({ minimum: 0 })) }, { additionalProperties: false }),
};
const desktopOutput = `${JSON.stringify({ apiVersion: 'v1', schemaVersion: 1, operations, requestSchemas }, null, 2)}\n`;
const typeRows = operations.map((operation) => `  ${JSON.stringify(operation)},`).join('\n');
const typescriptOutput = `/* Generated by scripts/generate-api-v1-contract.mjs. Do not edit. */\nexport const API_V1_OPERATIONS = [\n${typeRows}\n] as const;\n\nexport type ApiV1Operation = typeof API_V1_OPERATIONS[number];\nexport type ApiV1OperationId = ApiV1Operation['operationId'];\n`;

function verify(path, expected) {
  let actual = '';
  try { actual = readFileSync(path, 'utf8'); } catch { /* reported below */ }
  if (actual !== expected) throw new Error(`${path} is stale. Run npm run api:v1:generate.`);
}

if (check) {
  verify(desktopOutputPath, desktopOutput);
  verify(typescriptOutputPath, typescriptOutput);
} else {
  writeFileSync(desktopOutputPath, desktopOutput);
  writeFileSync(typescriptOutputPath, typescriptOutput);
}

console.log(JSON.stringify({ operations: operations.length, check }));
