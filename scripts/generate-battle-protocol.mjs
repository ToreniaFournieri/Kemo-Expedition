import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const definitionPath = resolve(root, 'native/battle_protocol.def');
const headerPath = resolve(root, 'native/generated/battle_protocol.generated.h');
const typescriptPath = resolve(root, 'src/game/generated/battleProtocol.generated.ts');
const check = process.argv.includes('--check');

if (!check) {
  mkdirSync(dirname(headerPath), { recursive: true });
  mkdirSync(dirname(typescriptPath), { recursive: true });
}

const groups = { ABILITY: [], TERRAIN: [], EVENT: [], DEITY: [], ACTION: [] };
for (const [index, rawLine] of readFileSync(definitionPath, 'utf8').split(/\r?\n/u).entries()) {
  const line = rawLine.trim();
  if (!line || line.startsWith('#')) continue;
  const match = /^(ABILITY|TERRAIN|EVENT|DEITY|ACTION)\((\d+),\s*([^)]+)\)$/u.exec(line);
  if (!match) throw new Error(`Invalid battle protocol definition at line ${index + 1}: ${rawLine}`);
  const [, kind, rawId, name] = match;
  const id = Number.parseInt(rawId, 10);
  if (id !== groups[kind].length + 1) throw new Error(`${kind} IDs must remain contiguous and append-only; expected ${groups[kind].length + 1}, received ${id}`);
  if (groups[kind].some((entry) => entry.name === name)) throw new Error(`Duplicate ${kind} name: ${name}`);
  groups[kind].push({ id, name });
}

const cppName = (value) => value
  .replace(/^terrain\./u, '')
  .split(/[._-]/u)
  .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
  .join('');

const cppEnum = (name, values) => [
  `enum class ${name} : unsigned short {`,
  '  None = 0,',
  ...values.map(({ id, name }) => `  ${cppName(name)} = ${id},`),
  '};',
].join('\n');

